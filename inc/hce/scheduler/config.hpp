#include <cstddef>

namespace hce {
namespace config {
namespace scheduler {

/**
 @brief object for configuring runtime behavior of a `scheduler`

 An instance of this object passed to `scheduler::make()` will configure 
 the scheduler during its runtime with the given event handlers and options.

 Unless the user manually creates new schedulers with `scheduler::make()`, 
 then most instances of `config` will be generated by 
 `hce::config::global::scheduler_config()` (and 
 `hce::config::threadpool::scheduler_config()`) when the framework is 
 constructing managed `scheduler`s. Said functions are `extern`and can be 
 overridden if `cmake` is configured with the `HCECUSTOMCONFIG` definition, 
 requiring the user to link their own implementation.
 */
struct config {
    config();

    /**
     Set the log level of the thread the scheduler is installed on.

     Maximum value: 9
     Minimum value: -9
     */
    int loglevel;

    /**
     The count of coroutine handles the scheduler can pool for reuse 
     without deallocating. A sane value (roughly equal or above the median count 
     of executing coroutines during busy periods) allows avoiding unnecessary 
     re-allocation of handles during normal operation. 

     This only potentially affects the scheduler's throughput processing 
     efficiency, it has no effect on the underlying coroutine execution.

     Handles are very small allocations (pointer sized).
     */
    size_t reusable_coroutine_handle_limit;
};

namespace global {

/**
 @brief provide the global scheduler configuration

 This `config` is used when constructing the process wide, default `scheduler` 
 (IE, the `scheduler` returned from 
 `scheduler::global::service::get().scheduler()`).

 @return a copy of the global scheduler configuration 
 */
hce::config::scheduler::config config();

}

} // scheduler
} // config
} // hce
